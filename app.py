from flask import Flask

# Создаем приложение
app = Flask(__name__)

# Декоратор @app.route говорит: "Когда кто-то зайдет на главную страницу (/), выполни эту функцию"


@app.route("/")
def home():
    return "<h1>Привет! Это мой первый сервер на Flask!</h1>"


# Если файл запускают напрямую (а не импортируют)
if __name__ == "__main__":
    # Запускаем сервер в режиме отладки (debug=True)
    app.run(debug=True)
